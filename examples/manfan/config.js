const 附加注 = { 'β-B': '这一档没有同伴，也不会遇见任何人。' };

function 档案正文(名字, 玩家段, 起点) {
  const 身 = 玩家段?.身份 || {};
  const 属 = 玩家段?.属性 || {};
  const 技 = 玩家段?.技能 || [];
  const 装 = 玩家段?.装备 || {};

  const 职业行 = [
    身.战斗职业 ? 身.战斗职业 + '（战斗）' : null,
    身.生活职业 ? 身.生活职业 + '（生活）' : null,
    身.副业 ? 身.副业 + '（副业）' : null,
  ].filter(Boolean).join('　') || '（没有职业）';

  return [
    '[主角档案]',
    '',
    (名字 || '无名') + ' · ' + (身.种族 || '长身人') + ' · ' + (身.年龄 || 20) + ' 岁',
    '职业：' + 职业行,
    '',
    '六项：' + 属性键.map((k) => k + ' ' + (属[k] == null ? 50 : 属[k])).join(' / '),
    '技能：' + (技.length ? 技.map((s) => s.name + ' +' + s.value).join('、') : '（无）'),
    '装备：' + ([装.武器, 装.防具, 装.饰品].filter(Boolean).join('、') || '（空手）'),
    '',
    '欲念：' + (玩家段?.欲念 || '（还没想清楚）'),
    '开局：' + (开局行[起点] || ''),
    '',
    '注：血量、位置、在场、好感以变量为准，本节只描述这个人是谁。' +
      (附加注[起点] ? '　' + 附加注[起点] : ''),
  ].join('\n');
}

