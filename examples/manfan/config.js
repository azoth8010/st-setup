function 消息正文(名字, 玩家段, 起点) {
  const 锚 = 锚点信息[起点];
  if (!锚) throw new Error('未知起点：' + 起点);
  const 身 = 玩家段?.身份 || {};
  const 属 = 玩家段?.属性 || {};
  const 生 = 玩家段?.生命 || {};
  const 技 = 玩家段?.技能 || [];

  const 职业 = (身.战斗职业 || '') + (身.生活职业 ? ' / ' + 身.生活职业 : '') +
               (身.副业 ? '（副 ' + 身.副业 + '）' : '');

  const 行 = [
    '我是' + (名字 || '无名') + '，' + (身.种族 || '长身人') + '，' + 职业 + '。',
    '（' + 属性键.map((k) => k + ' ' + (属[k] == null ? 50 : 属[k])).join(' · ') + '）',
    '（' + (技.length ? 技.map((s) => s.name + ' +' + s.value).join(' · ') : '（无）') +
      '　HP ' + (生.当前HP || 0) + '/' + (生.最大HP || 0) +
      '　MP ' + (生.当前MP || 0) + '/' + (生.最大MP || 0) +
      '　金钱 ' + (玩家段?.金钱 != null ? 玩家段.金钱 : 0) + ' G）',
    '',
    '（时间：' + 锚.时间 + '）',
    '（前情：' + 锚.前情 + '）',
    '（所见：' + 锚.所见 + '）',
  ];
  if (锚.约束) 行.push(锚.约束);
  return 行.join('\n');
}

