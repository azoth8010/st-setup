/* ---------------- 派生 ---------------- */

const 数 = (v, d) => (Number.isFinite(Number(v)) ? Number(v) : d);

function 派生(tree, 玩家) {
  const p = tree.玩家 || (tree.玩家 = {});
  const 属性 = p.属性 || (p.属性 = {});
  const 生命 = p.生命 || (p.生命 = {});
  const 满血 = !(玩家 && 玩家.生命);

  生命.最大HP = Math.max(1, Math.round(20 + 数(属性.体魄, 50) / 2));
  生命.最大MP = Math.max(0, Math.round(数(属性.学识, 50) / 2 + 数(属性.意志, 50) / 4));
  生命.当前HP = 满血 ? 生命.最大HP : Math.min(Math.max(0, 数(生命.当前HP, 生命.最大HP)), 生命.最大HP);
  生命.当前MP = 满血 ? 生命.最大MP : Math.min(Math.max(0, 数(生命.当前MP, 生命.最大MP)), 生命.最大MP);

  const 技能 = Array.isArray(p.技能) ? p.技能 : (p.技能 = []);
  技能.forEach((s, i) => { if (!s.uid) s.uid = 'sk_' + (i + 1); });
  tree._nextUid = 技能.length + 1;
}

/* ---------------- 额外验收 ---------------- */

function 额外验收(tree) {
  const 查长 = (obj, 字段, 名) => {
    Object.entries(obj || {}).forEach(([k, v]) => {
      const s = v?.[字段];
      if (typeof s === 'string' && s.length > 文上限) {
        throw new Error(`${名} ${k} 的${字段} ${s.length} 字，超过 ${文上限}`);
      }
    });
  };

  for (const [名, 人] of Object.entries(tree.人物 || {})) {
    ['身份', '好感', '关系', '欲念', '同行'].forEach((f) => {
      if (!(f in 人)) throw new Error(`人物 ${名} 缺 ${f}`);
    });
  }
  for (const [名, 人] of Object.entries(tree.在场 || {})) {
    ['此刻状态', '心声'].forEach((f) => {
      if (!(f in 人)) throw new Error(`在场 ${名} 缺 ${f}`);
    });
  }
  if (Object.keys(tree.在场 || {}).length > 6) throw new Error('在场超过 6 条');
  if (Object.keys(tree.委托 || {}).length > 5) throw new Error('委托超过 5 条');

  查长(tree.人物, '关系', '人物');
  查长(tree.人物, '欲念', '人物');
  查长(tree.在场, '此刻状态', '在场');
  查长(tree.在场, '心声', '在场');
}

